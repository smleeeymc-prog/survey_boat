// 배 모델의 "기본 뱃머리 방향" 보정값 — 블렌더에서 뽑은 Ship의 정면이 코드가 가정하는
// +X 축과 다를 때 여기서만 맞춘다. 헤딩 로직은 건드리지 않으므로
// "0 = 섬(+X)을 향함 / Math.PI = 섬을 등짐" 이라는 의미가 그대로 유지된다.
// 모델을 다시 뽑아서 방향이 또 달라지면 0 / ±Math.PI/2 / Math.PI 중에서 이 값만 바꿀 것.
export const SHIP_FORWARD_OFFSET = Math.PI;

// 흘수(배가 물에 잠기는 깊이). Ship 원점이 선체 중간쯤이라 0으로 두면 절반이 잠긴다.
// 선체(Ship Body)는 원점 기준 y −0.225 ~ +0.212, 즉 높이 0.437.
// 파도를 세게 하거나 모델을 다시 뽑으면 다른 데 건드리지 말고 이 숫자만 조절할 것.
// 배 크기에 비례해서 같이 곱해야 잠기는 "비율"이 유지된다.
export const SHIP_DRAFT = 0.17;

// GLB에서 찾아 쓰는 노드 이름. 블렌더에서 이름이 바뀌면 두 화면이 같이 조용히 깨지므로
// 여기 한 곳에 모아 둔다. (지도의 selfcheck.js가 로드마다 존재를 확인한다)
export const SHIP_NODES = {
  ship: "Ship",
  cabin: "Cabin",
  funnel: "Funnel",
  props: { Seagull: "gull", Tube: "tube" },
};

